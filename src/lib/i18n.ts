const DICTS: Record<Lang, Dict> = { fr: FR, en: EN, es: ES }

/** Langue du navigateur, utilisée quand le réglage est absent. */
export function detectLang(): Lang {
  const nav = (navigator.language || 'fr').slice(0, 2)
  return nav === 'en' ? 'en' : nav === 'es' ? 'es' : 'fr'
}

/** Langue active de l'interface. */
export function useLang(): Lang {
  const lang = useStore((s) => s.settings.lang)
  return lang ?? detectLang()
}

/** Traducteur : t('nav.hero'), avec variables {n} optionnelles. */
export function useT() {
  const lang = useLang()
  return (key: string, vars?: Record<string, string | number>) => {
    let out = DICTS[lang][key] ?? FR[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v))
    }
    return out
  }
}
